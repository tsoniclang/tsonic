import { assert, cliPath, resolve, runGeneratedProject, runNode, tempRoot, test, writeProject } from "../../helpers/harness.mjs";

test("CLI runs generated C# executable for nullish, optional, flow, ternary, and void semantics", async () => {
  const assemblyName = "SmokeGeneratedE2EControlFlow";
  const projectDirectory = resolve(tempRoot, "e2e-control-flow");
  await writeProject(projectDirectory, {
    "tsonic.json": JSON.stringify({
      entryPoint: "index.ts",
      rootDir: "src",
      outDir: "out",
      targets: [
        {
          id: "csharp",
          surfaces: ["js"],
          options: {
            namespace: "Smoke.Generated",
            assemblyName,
            outputType: "Exe",
          },
        },
      ],
    }, null, 2),
    "src/index.ts": [
      "import type { int } from \"@tsonic/csharp/types.js\";",
      "import { Console } from \"@tsonic/dotnet/System.js\";",
      "",
      "class Box {",
      "  value: number = 5;",
      "  read(): number {",
      "    return this.value;",
      "  }",
      "}",
      "class Address {",
      "  city: string = \"Paris\";",
      "}",
      "class User {",
      "  name: string = \"Ada\";",
      "  address: Address | null = new Address();",
      "}",
      "",
      "function lengthOrZero(value: string | null): number {",
      "  if (typeof value === \"string\") {",
      "    return value.length;",
      "  }",
      "  return 0;",
      "}",
      "",
      "function fallbackString(value: string | null): string {",
      "  return value ?? \"missing\";",
      "}",
      "",
      "function fallbackInt(value: int | null): int {",
      "  return value ?? 42;",
      "}",
      "",
      "function fallbackNumber(value: number | null): number {",
      "  return value ?? 42;",
      "}",
      "",
      "function optionalValue(box: Box | null): number {",
      "  return box?.value ?? 9;",
      "}",
      "",
      "function optionalCall(box: Box | null): number {",
      "  return box?.read() ?? 11;",
      "}",
      "",
      "function optionalCity(user: User | null): string {",
      "  return user?.address?.city ?? \"none\";",
      "}",
      "",
      "function optionalNameLength(user: User | null): number {",
      "  return user?.name.length ?? 0;",
      "}",
      "",
      "function optionalElement(values: int[] | null, index: int): int {",
      "  return values?.[index] ?? 99;",
      "}",
      "",
      "function classify(value: int): string {",
      "  if (value < 0) {",
      "    return \"negative\";",
      "  }",
      "  if (value === 0) {",
      "    return \"zero\";",
      "  }",
      "  return \"positive\";",
      "}",
      "",
      "function chooseInt(flag: boolean): int {",
      "  return flag ? 7 : 8;",
      "}",
      "",
      "function chooseNumber(flag: boolean): number {",
      "  return flag ? 1 : 2.5;",
      "}",
      "",
      "function returnIntInFlow(value: int): int {",
      "  if (value > 0) {",
      "    return 10;",
      "  }",
      "  return 20;",
      "}",
      "",
      "function getInIf(condition: boolean): int {",
      "  if (condition) {",
      "    return 7 / 2;",
      "  }",
      "  return 100;",
      "}",
      "",
      "function getInElse(condition: boolean): int {",
      "  if (condition) {",
      "    return 10;",
      "  } else {",
      "    return 9 / 2;",
      "  }",
      "}",
      "",
      "function getInWhile(count: int): int {",
      "  while (count > 0) {",
      "    return 15 / 4;",
      "  }",
      "  return 0;",
      "}",
      "",
      "function getInFor(): int {",
      "  for (let i: int = 0; i < 10; i++) {",
      "    return 11 / 3;",
      "  }",
      "  return 0;",
      "}",
      "",
      "function getInSwitch(key: int): int {",
      "  switch (key) {",
      "    case 1:",
      "      return 13 / 4;",
      "    case 2:",
      "      return 17 / 5;",
      "    default:",
      "      return 19 / 6;",
      "  }",
      "}",
      "",
      "function getInNestedIf(a: boolean, b: boolean): int {",
      "  if (a) {",
      "    if (b) {",
      "      return 21 / 7;",
      "    }",
      "    return 100;",
      "  }",
      "  return 200;",
      "}",
      "",
      "function getWithNullish(value: int | null): int {",
      "  return value ?? 25 / 2;",
      "}",
      "",
      "function getFirstValid(a: int | null, b: int | null): int {",
      "  return a ?? b ?? 333;",
      "}",
      "",
      "function divideOrDefault(value: int | null, divisor: int): int {",
      "  return value ?? 10 / divisor;",
      "}",
      "",
      "function nullishWithExpr(value: int | null, fallback: int): int {",
      "  return value ?? fallback;",
      "}",
      "",
      "function nullishInVar(value: int | null): int {",
      "  const result: int = value ?? 42;",
      "  return result;",
      "}",
      "",
      "function nullishInIf(value: int | null, condition: boolean): int {",
      "  if (condition) {",
      "    return value ?? 50;",
      "  }",
      "  return value ?? 60;",
      "}",
      "",
      "function ternaryReturn(flag: boolean): int {",
      "  return flag ? 100 : 200;",
      "}",
      "",
      "function expectedIntThreading(): void {",
      "  const a: int = 7;",
      "  const b: int = 2;",
      "  const divResult: int = true ? a / b : 0;",
      "  const nested: int = true ? (false ? 1 : 2) : 3;",
      "  const deepNest: int = true ? (true ? (false ? 10 : 20) : 30) : 40;",
      "  const x: int = 10;",
      "  const y: int = 20;",
      "  const withArith: int = true ? x + 5 : y - 5;",
      "  let mutableInt: int = 0;",
      "  mutableInt = true ? 42 : 0;",
      "  Console.WriteLine(`return if: ${getInIf(true)}`);",
      "  Console.WriteLine(`return else: ${getInElse(false)}`);",
      "  Console.WriteLine(`return while: ${getInWhile(1)}`);",
      "  Console.WriteLine(`return for: ${getInFor()}`);",
      "  Console.WriteLine(`return switch: ${getInSwitch(1)}, ${getInSwitch(2)}, ${getInSwitch(99)}`);",
      "  Console.WriteLine(`return nested: ${getInNestedIf(true, true)}`);",
      "  Console.WriteLine(`return nullish: ${getWithNullish(null)}`);",
      "  Console.WriteLine(`first valid: ${getFirstValid(null, null)}, ${getFirstValid(null, 50)}, ${getFirstValid(25, 50)}`);",
      "  Console.WriteLine(`divide default: ${divideOrDefault(null, 3)}, ${divideOrDefault(99, 3)}`);",
      "  Console.WriteLine(`nullish expr: ${nullishWithExpr(null, 77)}, ${nullishWithExpr(88, 77)}`);",
      "  Console.WriteLine(`nullish var: ${nullishInVar(null)}, ${nullishInVar(99)}`);",
      "  Console.WriteLine(`nullish if: ${nullishInIf(null, true)}, ${nullishInIf(null, false)}, ${nullishInIf(70, false)}`);",
      "  Console.WriteLine(`ternary divide: ${divResult}`);",
      "  Console.WriteLine(`ternary nested: ${nested}, ${deepNest}`);",
      "  Console.WriteLine(`ternary return: ${ternaryReturn(true)}, ${ternaryReturn(false)}`);",
      "  Console.WriteLine(`ternary arithmetic: ${withArith}`);",
      "  Console.WriteLine(`ternary assignment: ${mutableInt}`);",
      "}",
      "",
      "function trace(value: string): number {",
      "  Console.WriteLine(`trace:${value}`);",
      "  return 123;",
      "}",
      "",
      "function runVoid(): void {",
      "  void trace(\"voided\");",
      "  Console.WriteLine(\"after void\");",
      "}",
      "",
      "const box = new Box();",
      "const user = new User();",
      "Console.WriteLine(`length string: ${lengthOrZero(\"abcd\")}`);",
      "Console.WriteLine(`length null: ${lengthOrZero(null)}`);",
      "Console.WriteLine(`fallback string: ${fallbackString(\"kept\")}`);",
      "Console.WriteLine(`fallback string null: ${fallbackString(null)}`);",
      "Console.WriteLine(`fallback int: ${fallbackInt(7)}`);",
      "Console.WriteLine(`fallback int null: ${fallbackInt(null)}`);",
      "Console.WriteLine(`fallback value: ${fallbackNumber(3.5)}`);",
      "Console.WriteLine(`fallback null: ${fallbackNumber(null)}`);",
      "Console.WriteLine(`optional value: ${optionalValue(box)}`);",
      "Console.WriteLine(`optional value null: ${optionalValue(null)}`);",
      "Console.WriteLine(`optional call: ${optionalCall(box)}`);",
      "Console.WriteLine(`optional call null: ${optionalCall(null)}`);",
      "Console.WriteLine(`optional city: ${optionalCity(user)}`);",
      "Console.WriteLine(`optional city null: ${optionalCity(null)}`);",
      "Console.WriteLine(`optional name length: ${optionalNameLength(user)}`);",
      "Console.WriteLine(`optional name length null: ${optionalNameLength(null)}`);",
      "Console.WriteLine(`optional element: ${optionalElement([4, 5, 6], 1)}`);",
      "Console.WriteLine(`optional element null: ${optionalElement(null, 1)}`);",
      "Console.WriteLine(`classify negative: ${classify(-1)}`);",
      "Console.WriteLine(`classify zero: ${classify(0)}`);",
      "Console.WriteLine(`classify positive: ${classify(2)}`);",
      "Console.WriteLine(`choose int: ${chooseInt(true)}, ${chooseInt(false)}`);",
      "Console.WriteLine(`choose number: ${chooseNumber(true)}, ${chooseNumber(false)}`);",
      "Console.WriteLine(`return flow int: ${returnIntInFlow(1)}, ${returnIntInFlow(0)}`);",
      "expectedIntThreading();",
      "runVoid();",
      "",
    ].join("\n"),
  });

  const build = runNode([cliPath, "build", "--project", resolve(projectDirectory, "tsonic.json")]);
  assert.equal(build.status, 0, build.stdout + build.stderr);
  assert.equal(runGeneratedProject(projectDirectory, assemblyName), [
    "length string: 4",
    "length null: 0",
    "fallback string: kept",
    "fallback string null: missing",
    "fallback int: 7",
    "fallback int null: 42",
    "fallback value: 3.5",
    "fallback null: 42",
    "optional value: 5",
    "optional value null: 9",
    "optional call: 5",
    "optional call null: 11",
    "optional city: Paris",
    "optional city null: none",
    "optional name length: 3",
    "optional name length null: 0",
    "optional element: 5",
    "optional element null: 99",
    "classify negative: negative",
    "classify zero: zero",
    "classify positive: positive",
    "choose int: 7, 8",
    "choose number: 1, 2.5",
    "return flow int: 10, 20",
    "return if: 3",
    "return else: 4",
    "return while: 3",
    "return for: 3",
    "return switch: 3, 3, 3",
    "return nested: 3",
    "return nullish: 12",
    "first valid: 333, 50, 25",
    "divide default: 3, 99",
    "nullish expr: 77, 88",
    "nullish var: 42, 99",
    "nullish if: 50, 60, 70",
    "ternary divide: 3",
    "ternary nested: 2, 20",
    "ternary return: 100, 200",
    "ternary arithmetic: 15",
    "ternary assignment: 42",
    "trace:voided",
    "after void",
    "",
  ].join("\n"));
});
