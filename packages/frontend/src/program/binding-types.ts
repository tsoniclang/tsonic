/**
 * Binding manifest types - maps JS/TS names to external target types/members
 * See spec/bindings.md for full manifest format
 */

import type {
  IrOverloadFamilyMember,
  IrParameter,
  IrType,
} from "../ir/index.js";

/**
 * Parameter modifier for ref/out/in parameters
 * Matches the format from tsbindgen: { index: number, modifier: "ref" | "out" | "in" }
 */
export type ParameterModifier = {
  readonly index: number;
  readonly modifier: "ref" | "out" | "in";
};

export type EmitCallStyle = "receiver" | "static";
export type EmitCallableStaticAccessorKind = "property" | "field";

export type EmitSemantics = {
  readonly callStyle?: EmitCallStyle;
  readonly callableStaticAccessorKind?: EmitCallableStaticAccessorKind;
};

export type TypeSemantics = {
  readonly contributesTypeIdentity: boolean;
};

export type BindingSemanticSignature = {
  readonly typeParameters?: readonly string[];
  readonly parameters: readonly IrParameter[];
  readonly returnType?: IrType;
};

export type BindingOverloadFamily = IrOverloadFamilyMember;

/**
 * Member binding (method/property level)
 */
export type MemberBinding = {
  readonly kind: "method" | "property";
  readonly stableId?: string;
  readonly signature?: string; // Optional TS signature for diagnostics
  readonly semanticType?: IrType;
  readonly semanticOptional?: boolean;
  readonly semanticSignature?: BindingSemanticSignature;
  readonly receiverExpectedType?: IrType;
  readonly overloadFamily?: BindingOverloadFamily;
  /** Total target parameter count (includes extension receiver for extension methods). */
  readonly parameterCount?: number;
  readonly name: string; // Target member name (e.g., "SelectMany")
  readonly alias: string; // TS identifier (e.g., "selectMany")
  readonly binding: {
    readonly ownerIdentity: string;
    readonly type: string; // Full target type name (e.g., "Provider.Linq.Enumerable")
    readonly member: string; // Target member name
  };
  // Parameter modifiers for ref/out/in parameters (from tsbindgen)
  readonly parameterModifiers?: readonly ParameterModifier[];
  // Whether this member is an extension method (tsbindgen metadata).
  // Used by the emitter to lower instance-style calls to explicit static calls.
  readonly isExtensionMethod?: boolean;
  readonly emitSemantics?: EmitSemantics;
  readonly sourceOrigin?: {
    readonly filePath: string;
    readonly exportName: string;
    readonly memberName?: string;
  };
};

/**
 * Type binding (class/interface/struct/enum level)
 */
export type TypeBinding = {
  readonly stableId?: string;
  readonly stableIds?: readonly string[];
  readonly name: string; // Target type name (e.g., "Enumerable")
  readonly alias: string; // TS identifier (e.g., "enumerable")
  readonly kind: "class" | "interface" | "struct" | "enum" | "delegate";
  readonly members: readonly MemberBinding[];
};

/**
 * Namespace binding
 */
export type NamespaceBinding = {
  readonly name: string; // external namespace (e.g., "Provider.Linq")
  readonly alias: string; // TS identifier (e.g., "systemLinq")
  readonly types: readonly TypeBinding[];
};

/**
 * Simple binding entry for global/module identifiers
 * Maps identifiers like `console`, `Math`, `fs` to external target types
 */
export type SimpleBindingDescriptor = {
  readonly kind: "global" | "module";
  readonly ownerIdentity: string;
  readonly type: string;
  readonly sourceImport?: string; // Optional: resolve the binding through a source-package import instead of a target module type
  readonly staticType?: string; // Optional: separate target type for static member access
  readonly providerMemberName?: string; // Optional target member name for generated calls/references
  readonly typeSemantics?: TypeSemantics;
};

/**
 * External target binding format - generated by binding providers.
 */
export type TsbindgenMethod = {
  readonly stableId?: string;
  readonly targetName: string;
  /** Normalized signature string (tsbindgen metadata, used for extension receiver inference) */
  readonly normalizedSignature?: string;
  readonly semanticSignature?: BindingSemanticSignature;
  readonly overloadFamily?: BindingOverloadFamily;
  /** Total parameter count in target signature (includes extension receiver) */
  readonly parameterCount?: number;
  readonly ownerQualifiedName?: string;
  readonly ownerIdentity?: string;
  // Parameter modifiers for ref/out/in parameters
  readonly parameterModifiers?: readonly ParameterModifier[];
  readonly isExtensionMethod?: boolean;
  readonly emitSemantics?: EmitSemantics;
};

export type TsbindgenProperty = {
  readonly stableId?: string;
  readonly targetName: string;
  readonly normalizedSignature?: string;
  readonly semanticType?: IrType;
  readonly semanticOptional?: boolean;
  readonly ownerQualifiedName?: string;
  readonly ownerIdentity?: string;
  readonly emitSemantics?: EmitSemantics;
};

export type TsbindgenField = {
  readonly stableId?: string;
  readonly targetName: string;
  readonly normalizedSignature?: string;
  readonly semanticType?: IrType;
  readonly semanticOptional?: boolean;
  readonly ownerQualifiedName?: string;
  readonly ownerIdentity?: string;
  readonly emitSemantics?: EmitSemantics;
};

export type TsbindgenTypeRef = {
  readonly stableId?: string;
  readonly targetName: string;
  readonly typeArguments?: readonly string[];
};

export type TsbindgenType = {
  readonly stableId?: string;
  readonly targetName: string; // Full target type name (e.g., "Provider.Console")
  readonly alias?: string; // Optional explicit TS lookup alias from provider bindings
  readonly ownerIdentity: string;
  readonly baseType?: TsbindgenTypeRef;
  readonly interfaces?: readonly TsbindgenTypeRef[];
  /**
   * Target type kind from the binding provider (e.g., "Class", "Interface", "Struct", "Enum", "Delegate").
   *
   * This is used for airplane-grade emission decisions (e.g., whether a name in
   * a TS `implements` clause is a target interface and should be emitted in the target
   * heritage list).
   */
  readonly kind?: "Class" | "Interface" | "Struct" | "Enum" | "Delegate";
  readonly methods: readonly TsbindgenMethod[];
  readonly properties: readonly TsbindgenProperty[];
  readonly fields: readonly TsbindgenField[];
};

/**
 * tsbindgen "flattened named export" descriptor.
 *
 * This is an additive surface to support JS-style named imports that bind to
 * a stable declaring target type + member (typically module container static types).
 *
 * Example (user code):
 *   import { buildSite } from "@tsumo/engine/Tsumo.Engine.js";
 *   buildSite(req);
 *
 * Example (bindings.json excerpt):
 *   "exports": {
 *     "buildSite": {
 *       "kind": "method",
 *       "targetName": "buildSite",
 *       "ownerQualifiedName": "Tsumo.Engine.BuildSite",
 *       "ownerIdentity": "Tsumo.Engine"
 *     }
 *   }
 */
export type TsbindgenExport = {
  readonly kind: "method" | "property" | "field" | "functionType";
  readonly stableId?: string;
  readonly targetName: string;
  readonly ownerQualifiedName: string;
  readonly ownerIdentity: string;
  readonly semanticType?: IrType;
  readonly semanticOptional?: boolean;
  readonly semanticSignature?: BindingSemanticSignature;
};

export const TSONIC_BINDINGS_SCHEMA = "tsonic.bindings";

export type BindingProviderDescriptor = {
  readonly namespace: string;
  readonly ownerIdentities?: readonly string[];
  readonly targetRuntimeVersion?: string;
};

export type BindingSourceSurface = {
  readonly bindings?: Readonly<Record<string, SimpleBindingDescriptor>>;
  readonly namespaces?: readonly NamespaceBinding[];
};

export type BindingTargetSurface = {
  readonly types: readonly TsbindgenType[];
  readonly exports?: Readonly<Record<string, TsbindgenExport>>;
};

export type BindingFile = {
  readonly schema: typeof TSONIC_BINDINGS_SCHEMA;
  readonly provider: BindingProviderDescriptor;
  readonly sourceSurface?: BindingSourceSurface;
  readonly targetSurface: BindingTargetSurface;
};

const isValidEmitCallStyle = (value: unknown): value is EmitCallStyle =>
  value === "receiver" || value === "static";

const isValidEmitCallableStaticAccessorKind = (
  value: unknown
): value is EmitCallableStaticAccessorKind =>
  value === "property" || value === "field";

const validateEmitSemantics = (
  value: unknown,
  filePath: string,
  label: string
): string | undefined => {
  if (value === undefined) return undefined;
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    return `${filePath}: '${label}' must be an object`;
  }

  const record = value as Record<string, unknown>;
  if (
    "callStyle" in record &&
    record.callStyle !== undefined &&
    !isValidEmitCallStyle(record.callStyle)
  ) {
    return `${filePath}: '${label}.callStyle' must be 'receiver' or 'static'`;
  }
  if (
    "callableStaticAccessorKind" in record &&
    record.callableStaticAccessorKind !== undefined &&
    !isValidEmitCallableStaticAccessorKind(record.callableStaticAccessorKind)
  ) {
    return `${filePath}: '${label}.callableStaticAccessorKind' must be 'property' or 'field'`;
  }
  if (
    record.callStyle === undefined &&
    record.callableStaticAccessorKind === undefined
  ) {
    return `${filePath}: '${label}' must define at least one known emit semantics property`;
  }

  return undefined;
};

const validateTypeSemantics = (
  value: unknown,
  filePath: string,
  label: string
): string | undefined => {
  if (value === undefined) return undefined;
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    return `${filePath}: '${label}' must be an object`;
  }

  const record = value as Record<string, unknown>;
  if (typeof record.contributesTypeIdentity !== "boolean") {
    return `${filePath}: '${label}.contributesTypeIdentity' must be a boolean`;
  }

  return undefined;
};

const validateBindingSemanticSignature = (
  value: unknown,
  filePath: string,
  label: string
): string | undefined => {
  if (value === undefined) return undefined;
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    return `${filePath}: '${label}' must be an object`;
  }

  const record = value as Record<string, unknown>;
  if (
    "typeParameters" in record &&
    record.typeParameters !== undefined &&
    !(
      Array.isArray(record.typeParameters) &&
      record.typeParameters.every((entry) => typeof entry === "string")
    )
  ) {
    return `${filePath}: '${label}.typeParameters' must be a string array when present`;
  }
  if (!Array.isArray(record.parameters)) {
    return `${filePath}: '${label}.parameters' must be an array`;
  }

  return undefined;
};

const validateTsbindgenExport = (
  value: unknown,
  filePath: string,
  label: string
): string | undefined => {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    return `${filePath}: '${label}' must be an object`;
  }

  const record = value as Record<string, unknown>;
  const kind = record.kind;
  if (
    kind !== "method" &&
    kind !== "property" &&
    kind !== "field" &&
    kind !== "functionType"
  ) {
    return `${filePath}: '${label}.kind' must be 'method', 'property', 'field', or 'functionType'`;
  }
  if (typeof record.targetName !== "string") {
    return `${filePath}: '${label}.targetName' must be a string`;
  }
  if (typeof record.ownerQualifiedName !== "string") {
    return `${filePath}: '${label}.ownerQualifiedName' must be a string`;
  }
  if (typeof record.ownerIdentity !== "string") {
    return `${filePath}: '${label}.ownerIdentity' must be a string`;
  }

  const semanticSignatureError = validateBindingSemanticSignature(
    record.semanticSignature,
    filePath,
    `${label}.semanticSignature`
  );
  if (semanticSignatureError) return semanticSignatureError;

  if (
    "semanticOptional" in record &&
    record.semanticOptional !== undefined &&
    typeof record.semanticOptional !== "boolean"
  ) {
    return `${filePath}: '${label}.semanticOptional' must be a boolean when present`;
  }

  return undefined;
};

/**
 * Validate that a parsed JSON object is a valid binding file format.
 * Returns an error message if invalid, undefined if valid.
 */
export const validateBindingFile = (
  obj: unknown,
  filePath: string
): string | undefined => {
  if (obj === null || typeof obj !== "object") {
    return `${filePath}: Expected object, got ${typeof obj}`;
  }

  const manifest = obj as Record<string, unknown>;

  if (manifest.schema !== TSONIC_BINDINGS_SCHEMA) {
    return `${filePath}: 'schema' must be '${TSONIC_BINDINGS_SCHEMA}'`;
  }

  if (
    manifest.provider === null ||
    typeof manifest.provider !== "object" ||
    Array.isArray(manifest.provider)
  ) {
    return `${filePath}: 'provider' must be an object`;
  }

  const provider = manifest.provider as Record<string, unknown>;
  if (typeof provider.namespace !== "string") {
    return `${filePath}: 'provider.namespace' must be a string`;
  }
  if (
    provider.ownerIdentities !== undefined &&
    !(
      Array.isArray(provider.ownerIdentities) &&
      provider.ownerIdentities.every((entry) => typeof entry === "string")
    )
  ) {
    return `${filePath}: 'provider.ownerIdentities' must be a string array when present`;
  }
  if (
    provider.targetRuntimeVersion !== undefined &&
    typeof provider.targetRuntimeVersion !== "string"
  ) {
    return `${filePath}: 'provider.targetRuntimeVersion' must be a string when present`;
  }

  if (
    manifest.targetSurface === null ||
    typeof manifest.targetSurface !== "object" ||
    Array.isArray(manifest.targetSurface)
  ) {
    return `${filePath}: 'targetSurface' must be an object`;
  }

  const targetSurface = manifest.targetSurface as Record<string, unknown>;
  if (!Array.isArray(targetSurface.types)) {
    return `${filePath}: 'targetSurface.types' must be an array`;
  }

  for (const [typeIndex, typeValue] of targetSurface.types.entries()) {
    if (typeValue === null || typeof typeValue !== "object") continue;
    const typeRecord = typeValue as Record<string, unknown>;
    if (
      "alias" in typeRecord &&
      typeRecord.alias !== undefined &&
      typeof typeRecord.alias !== "string"
    ) {
      return `${filePath}: 'targetSurface.types[${typeIndex}].alias' must be a string when present`;
    }
    const methods = Array.isArray(typeRecord.methods) ? typeRecord.methods : [];
    for (const [methodIndex, methodValue] of methods.entries()) {
      if (methodValue === null || typeof methodValue !== "object") continue;
      const error = validateEmitSemantics(
        (methodValue as Record<string, unknown>).emitSemantics,
        filePath,
        `targetSurface.types[${typeIndex}].methods[${methodIndex}].emitSemantics`
      );
      if (error) return error;
    }
  }

  if ("exports" in targetSurface) {
    const exportsValue = targetSurface.exports;
    if (
      exportsValue !== undefined &&
      (exportsValue === null ||
        typeof exportsValue !== "object" ||
        Array.isArray(exportsValue))
    ) {
      return `${filePath}: 'targetSurface.exports' must be an object when present`;
    }
    if (exportsValue && typeof exportsValue === "object") {
      for (const [exportName, exportValue] of Object.entries(exportsValue)) {
        const error = validateTsbindgenExport(
          exportValue,
          filePath,
          `targetSurface.exports.${exportName}`
        );
        if (error) return error;
      }
    }
  }

  if (manifest.sourceSurface !== undefined) {
    if (
      manifest.sourceSurface === null ||
      typeof manifest.sourceSurface !== "object" ||
      Array.isArray(manifest.sourceSurface)
    ) {
      return `${filePath}: 'sourceSurface' must be an object when present`;
    }

    const sourceSurface = manifest.sourceSurface as Record<string, unknown>;
    if (
      sourceSurface.bindings !== undefined &&
      (typeof sourceSurface.bindings !== "object" ||
        sourceSurface.bindings === null ||
        Array.isArray(sourceSurface.bindings))
    ) {
      return `${filePath}: 'sourceSurface.bindings' must be an object when present`;
    }
    if (sourceSurface.bindings && typeof sourceSurface.bindings === "object") {
      for (const [bindingName, bindingValue] of Object.entries(
        sourceSurface.bindings as Record<string, unknown>
      )) {
        if (bindingValue === null || typeof bindingValue !== "object") continue;
        const error = validateTypeSemantics(
          (bindingValue as Record<string, unknown>).typeSemantics,
          filePath,
          `sourceSurface.bindings.${bindingName}.typeSemantics`
        );
        if (error) return error;
      }
    }

    if (
      sourceSurface.namespaces !== undefined &&
      !Array.isArray(sourceSurface.namespaces)
    ) {
      return `${filePath}: 'sourceSurface.namespaces' must be an array when present`;
    }
    if (Array.isArray(sourceSurface.namespaces)) {
      for (const [
        namespaceIndex,
        namespaceValue,
      ] of sourceSurface.namespaces.entries()) {
        if (namespaceValue === null || typeof namespaceValue !== "object")
          continue;
        const namespaceRecord = namespaceValue as Record<string, unknown>;
        const types = Array.isArray(namespaceRecord.types)
          ? namespaceRecord.types
          : [];
        for (const [typeIndex, typeValue] of types.entries()) {
          if (typeValue === null || typeof typeValue !== "object") continue;
          const typeRecord = typeValue as Record<string, unknown>;
          const members = Array.isArray(typeRecord.members)
            ? typeRecord.members
            : [];
          for (const [memberIndex, memberValue] of members.entries()) {
            if (memberValue === null || typeof memberValue !== "object")
              continue;
            const error = validateEmitSemantics(
              (memberValue as Record<string, unknown>).emitSemantics,
              filePath,
              `sourceSurface.namespaces[${namespaceIndex}].types[${typeIndex}].members[${memberIndex}].emitSemantics`
            );
            if (error) return error;
          }
        }
      }
    }
  }

  return undefined;
};
